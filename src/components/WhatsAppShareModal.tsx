import React, { useState } from 'react';
import { TournamentState } from '../lib/fideSwissEngine';
import { generateWhatsAppShareMessage } from '../lib/tournamentVaultAndFeatures';

interface WhatsAppShareModalProps {
  isOpen: boolean;
  onClose: () => void;
  tournament: TournamentState;
}

export const WhatsAppShareModal: React.FC<WhatsAppShareModalProps> = ({
  isOpen,
  onClose,
  tournament,
}) => {
  const [copied, setCopied] = useState(false);

  if (!isOpen) return null;

  const shareText = generateWhatsAppShareMessage(tournament);

  const handleCopy = () => {
    navigator.clipboard.writeText(shareText);
    setCopied(true);
    setTimeout(() => setCopied(false), 2500);
  };

  const handleOpenWhatsApp = () => {
    const encoded = encodeURIComponent(shareText);
    window.open(`https://api.whatsapp.com/send?text=${encoded}`, '_blank');
  };

  return (
    <div className="modal-overlay" onClick={onClose}>
      <div className="modal-content" onClick={(e) => e.stopPropagation()} style={{ maxWidth: '620px' }}>
        {/* Header */}
        <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center', marginBottom: '1.25rem' }}>
          <div style={{ display: 'flex', alignItems: 'center', gap: '0.6rem' }}>
            <span style={{ fontSize: '1.6rem' }}>💬</span>
            <div>
              <h2 style={{ fontSize: '1.25rem', fontWeight: 800 }}>1-Click WhatsApp / Telegram Round Broadcaster</h2>
              <p style={{ fontSize: '0.8rem', color: 'var(--text-muted)' }}>
                Clean mobile-formatted text with pairing cards and player lookup links
              </p>
            </div>
          </div>
          <button onClick={onClose} className="drawer-close-btn">✕</button>
        </div>

        {/* Message Preview Box */}
        <div style={{ marginBottom: '1.25rem' }}>
          <label style={{ display: 'block', fontSize: '0.82rem', fontWeight: 700, marginBottom: '0.4rem', color: 'var(--text-secondary)' }}>
            MESSAGE PREVIEW (AUTOGENERATED):
          </label>
          <textarea
            readOnly
            value={shareText}
            rows={12}
            style={{
              width: '100%',
              padding: '0.85rem',
              borderRadius: '10px',
              border: '1px solid var(--border-subtle)',
              background: 'var(--bg-secondary)',
              color: 'var(--text-primary)',
              fontFamily: 'var(--font-mono)',
              fontSize: '0.82rem',
              lineHeight: 1.5,
              resize: 'none',
            }}
          />
        </div>

        {/* Action Buttons */}
        <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center' }}>
          <button onClick={handleOpenWhatsApp} className="btn btn-accent" style={{ gap: '0.5rem' }}>
            <span>📲 Open WhatsApp Web</span>
          </button>

          <div style={{ display: 'flex', gap: '0.5rem' }}>
            <button onClick={handleCopy} className="btn btn-primary">
              {copied ? '✓ Copied to Clipboard!' : '📋 Copy Text'}
            </button>
            <button onClick={onClose} className="btn btn-secondary">
              Close
            </button>
          </div>
        </div>
      </div>
    </div>
  );
};
